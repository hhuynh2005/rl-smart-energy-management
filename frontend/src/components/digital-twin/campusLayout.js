export function worldToMinimap(x, z, mapW = 190, mapH = 136) {
  const spanX = CAMPUS_BOUNDS.maxX - CAMPUS_BOUNDS.minX;
  const spanZ = CAMPUS_BOUNDS.maxZ - CAMPUS_BOUNDS.minZ;
  const nx = (x - CAMPUS_BOUNDS.minX) / spanX;
  const nz = (z - CAMPUS_BOUNDS.minZ) / spanZ;
  return {
    mx: Math.max(0, Math.min(mapW, nx * mapW)),
    my: Math.max(0, Math.min(mapH, nz * mapH)),
  };
}

export function minimapToWorld(mx, my, mapW = 190, mapH = 136) {
  const spanX = CAMPUS_BOUNDS.maxX - CAMPUS_BOUNDS.minX;
  const spanZ = CAMPUS_BOUNDS.maxZ - CAMPUS_BOUNDS.minZ;
  const nx = Math.max(0, Math.min(1, mx / mapW));
  const nz = Math.max(0, Math.min(1, my / mapH));
  return {
    x: CAMPUS_BOUNDS.minX + nx * spanX,
    z: CAMPUS_BOUNDS.minZ + nz * spanZ,
  };
}

export function clampWalkPosition(x, z) {
  return {
    x: Math.max(CAMPUS_BOUNDS.minX + 6, Math.min(CAMPUS_BOUNDS.maxX - 6, x)),
    z: Math.max(CAMPUS_BOUNDS.minZ + 6, Math.min(CAMPUS_BOUNDS.maxZ - 6, z)),
  };
}
